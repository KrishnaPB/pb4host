"""Passive technology fingerprinting from HTML and response headers.

Deliberately narrow: WordPress / WooCommerce / theme / page builder / caching / CDN / managed
host / PHP version. Everything comes from what a normal page load exposes.
"""

from __future__ import annotations

import re
from collections import Counter
from dataclasses import dataclass, field

_GENERATOR_RE = re.compile(
    r'<meta[^>]+name=["\']generator["\'][^>]+content=["\']([^"\']+)["\']', re.IGNORECASE
)
_GENERATOR_RE2 = re.compile(
    r'<meta[^>]+content=["\']([^"\']+)["\'][^>]+name=["\']generator["\']', re.IGNORECASE
)
_THEME_RE = re.compile(r"/wp-content/themes/([a-zA-Z0-9_.-]+)/", re.IGNORECASE)
_WP_VER_RE = re.compile(r"/wp-includes/[^\s\"'>]+\?ver=(\d+\.\d+(?:\.\d+)?)", re.IGNORECASE)
_PHP_RE = re.compile(r"PHP/(\d+\.\d+(?:\.\d+)?)", re.IGNORECASE)

PAGE_BUILDERS = [
    ("elementor", [r"/plugins/elementor/", r"\belementor-(?:section|widget|element|kit)\b"]),
    ("wpbakery", [r"/plugins/js_composer/", r"\bvc_row\b", r"\bwpb_wrapper\b"]),
    ("divi", [r"/themes/Divi/", r"\bet_pb_(?:section|row|module)\b", r"/plugins/divi-builder/"]),
    ("avada", [r"/themes/Avada/", r"/plugins/fusion-builder/", r"\bfusion-builder\b"]),
    ("beaver_builder", [r"/plugins/bb-plugin/", r"\bfl-builder\b"]),
    ("oxygen", [r"/plugins/oxygen/", r"\bct_section\b"]),
    ("bricks", [r"/themes/bricks/", r"\bbrxe-"]),
    ("block_editor", [r"\bwp-block-(?:group|columns|cover|buttons)\b"]),
]
CACHING = [
    ("wp_rocket", [r"This website is like a Rocket", r"/plugins/wp-rocket/", r"wp-rocket", r"/wp-content/cache/min/\d+/", r"data-minify=\"1\""]),
    ("litespeed_cache", [r"Page optimized by LiteSpeed Cache", r"/plugins/litespeed-cache/"]),
    ("w3_total_cache", [r"Performance optimized by W3 Total Cache"]),
    ("wp_super_cache", [r"Cached page generated by WP-Super-Cache", r"Dynamic page generated in"]),
    ("wp_fastest_cache", [r"WP Fastest Cache file was created"]),
    ("breeze", [r"Cache served by breeze", r"/plugins/breeze/"]),
    ("sg_optimizer", [r"/plugins/sg-cachepress/"]),
    ("hummingbird", [r"Hummingbird cache file", r"/plugins/hummingbird-performance/"]),
    ("autoptimize", [r"/plugins/autoptimize/", r"autoptimize_"]),
    ("nitropack", [r"nitropack", r"NitroPack"]),
]
CACHE_HEADERS = {
    "x-litespeed-cache": "litespeed_cache",
    "x-kinsta-cache": "kinsta_cache",
    "x-nginx-cache": "nginx_cache",
    "x-cache-handler": "server_cache",
    "x-cache-enabled": "server_cache",
    "x-proxy-cache": "proxy_cache",
    "x-varnish": "varnish",
    "cf-cache-status": None,  # Cloudflare only caches HTML when configured; handled below
    "x-cache": None,
}
MANAGED_HOST_HEADERS = [
    ("wpengine", lambda h: "wp engine" in h.get("x-powered-by", "").lower()
     or "wpengine" in h.get("x-powered-by", "").lower()),
    ("kinsta", lambda h: "x-kinsta-cache" in h or "kinsta" in h.get("x-edge-location", "").lower()),
    ("pantheon", lambda h: "x-pantheon-styx-hostname" in h or "x-styx-req-id" in h),
    ("flywheel", lambda h: any(k.startswith("x-fw-") for k in h) or "flywheel" in h.get("x-powered-by", "").lower()),
    ("pressable", lambda h: "pressable" in h.get("x-powered-by", "").lower()),
    ("wordpress_com", lambda h: "x-ac" in h and "wpcom" in h.get("x-ac", "").lower()),
    ("cloudways", lambda h: h.get("x-cache-handler", "").lower() in {"wp", "cache-enabler"}
     and "cloudways" in h.get("x-powered-by", "").lower()),
]
CDN_HEADERS = [
    ("cloudflare", lambda h: "cf-ray" in h or h.get("server", "").lower() == "cloudflare"),
    ("sucuri", lambda h: "x-sucuri-id" in h or "sucuri" in h.get("server", "").lower()),
    ("akamai", lambda h: any(k.startswith("x-akamai") for k in h) or "akamaighost" in h.get("server", "").lower()),
    ("cloudfront", lambda h: "x-amz-cf-id" in h),
    ("fastly", lambda h: "fastly" in h.get("x-served-by", "").lower() or "fastly" in h.get("via", "").lower()),
    ("imperva", lambda h: "incapsula" in h.get("x-cdn", "").lower() or "x-iinfo" in h),
    ("bunny", lambda h: "bunnycdn" in h.get("server", "").lower()),
]


@dataclass
class Fingerprint:
    cms: str | None = None
    cms_version: str | None = None
    cms_confidence: float = 0.0
    is_woocommerce: bool = False
    theme: str | None = None
    page_builder: str | None = None
    caching_layer: str | None = None
    cdn: str | None = None
    managed_host: str | None = None
    php_version: str | None = None
    server_header: str | None = None
    signals: list[str] = field(default_factory=list)
    markers: list[str] = field(default_factory=list)


def _generator(html: str) -> list[str]:
    return [m.strip() for m in _GENERATOR_RE.findall(html)] + [
        m.strip() for m in _GENERATOR_RE2.findall(html)
    ]


def fingerprint(html: str, headers: dict[str, str]) -> Fingerprint:
    fp = Fingerprint()
    h = {k.lower(): v for k, v in (headers or {}).items()}
    html = html or ""
    sample = html[:600_000]

    generators = _generator(sample)
    wp_markers: list[str] = []
    if re.search(r"/wp-content/", sample, re.IGNORECASE):
        wp_markers.append("wp-content path")
    if re.search(r"/wp-includes/", sample, re.IGNORECASE):
        wp_markers.append("wp-includes path")
    if any(g.lower().startswith("wordpress") for g in generators):
        wp_markers.append("generator meta")
    if re.search(r'rel=["\']https://api\.w\.org/["\']', sample, re.IGNORECASE) or "/wp-json/" in sample:
        wp_markers.append("REST API link")
    if "wp-emoji" in sample or "wp-block-library" in sample:
        wp_markers.append("core assets")
    link_header = h.get("link", "")
    if "api.w.org" in link_header:
        wp_markers.append("Link header")
    if wp_markers:
        fp.cms = "wordpress"
        fp.cms_confidence = min(1.0, 0.5 + 0.15 * len(wp_markers))
        fp.markers.extend(wp_markers)
        fp.signals.append("wordpress")
        for g in generators:
            m = re.match(r"wordpress\s+(\d+\.\d+(?:\.\d+)?)", g, re.IGNORECASE)
            if m:
                fp.cms_version = m.group(1)
                fp.signals.append("wp_version_exposed")
                break
        if not fp.cms_version:
            versions = Counter(_WP_VER_RE.findall(sample))
            if versions:
                ver, count = versions.most_common(1)[0]
                if count >= 2:
                    fp.cms_version = ver
                    fp.signals.append("wp_version_exposed")
    else:
        for g in generators:
            gl = g.lower()
            for name, key in (
                ("shopify", "shopify"), ("wix", "wix.com"), ("squarespace", "squarespace"),
                ("joomla", "joomla"), ("drupal", "drupal"), ("webflow", "webflow"),
                ("ghost", "ghost"), ("hubspot", "hubspot"), ("blogger", "blogger"),
                ("duda", "duda"), ("weebly", "weebly"), ("typo3", "typo3"),
            ):
                if key in gl:
                    fp.cms = name
                    fp.cms_confidence = 0.9
        if fp.cms is None:
            if "cdn.shopify.com" in sample:
                fp.cms, fp.cms_confidence = "shopify", 0.9
            elif "static.parastorage.com" in sample or "wixstatic.com" in sample:
                fp.cms, fp.cms_confidence = "wix", 0.9
            elif "static1.squarespace.com" in sample:
                fp.cms, fp.cms_confidence = "squarespace", 0.9
            elif "/sites/default/files/" in sample and "drupal" in sample.lower():
                fp.cms, fp.cms_confidence = "drupal", 0.7
            elif "/media/jui/" in sample or "/components/com_" in sample:
                fp.cms, fp.cms_confidence = "joomla", 0.7
            elif "webflow.js" in sample or "data-wf-site" in sample:
                fp.cms, fp.cms_confidence = "webflow", 0.8

    if fp.cms == "wordpress":
        if (
            re.search(r"/plugins/woocommerce/", sample, re.IGNORECASE)
            or re.search(r"\bwoocommerce\b", sample)
            or "wc-ajax" in sample
            or any(g.lower().startswith("woocommerce") for g in generators)
        ):
            fp.is_woocommerce = True
            fp.signals.append("woocommerce")
        themes = Counter(_THEME_RE.findall(sample))
        if themes:
            fp.theme = themes.most_common(1)[0][0].lower()
        for name, patterns in PAGE_BUILDERS:
            if any(re.search(p, sample, re.IGNORECASE) for p in patterns):
                fp.page_builder = name
                fp.signals.append(f"page_builder:{name}")
                break
        for name, patterns in CACHING:
            if any(re.search(p, sample, re.IGNORECASE) for p in patterns):
                fp.caching_layer = name
                break

    if fp.caching_layer is None:
        for header, name in CACHE_HEADERS.items():
            if header in h:
                if name:
                    fp.caching_layer = name
                    break
                value = h[header].lower()
                if header == "x-cache" and "hit" in value:
                    fp.caching_layer = "edge_cache"
                    break
                if header == "cf-cache-status" and value in {"hit", "stale", "revalidated"}:
                    fp.caching_layer = "cloudflare_cache"
                    break

    for name, test in MANAGED_HOST_HEADERS:
        try:
            if test(h):
                fp.managed_host = name
                fp.signals.append(f"managed_wp_host:{name}")
                if fp.caching_layer is None:
                    fp.caching_layer = f"{name}_platform"
                break
        except Exception:  # pragma: no cover - defensive
            continue
    for name, test in CDN_HEADERS:
        try:
            if test(h):
                fp.cdn = name
                fp.signals.append(f"cdn:{name}")
                break
        except Exception:  # pragma: no cover
            continue

    powered = h.get("x-powered-by", "")
    m = _PHP_RE.search(powered)
    if m:
        fp.php_version = m.group(1)
        fp.signals.append("php_exposed")
    server = h.get("server")
    if server:
        fp.server_header = server[:120]
        if "litespeed" in server.lower() and fp.caching_layer is None and "x-litespeed-cache" not in h:
            fp.signals.append("litespeed_server")

    if fp.cms == "wordpress" and fp.caching_layer is None:
        fp.signals.append("no_caching_detected")
    return fp
